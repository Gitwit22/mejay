export type IsrcGenerationConfig = {
  prefix: 'QTA3L'
  countryCode: 'QT'
  registrantCode: 'A3L'
}

/** Registrant prefix MEJay issues codes under. External registrations may never claim it. */
export const MEJAY_ISRC_PREFIX = 'QTA3L'

/** Reasons an externally-assigned ISRC can't be registered, or null when it is acceptable. */
export function externalIsrcProblem(isrc: string): string | null {
  const canonical = normalizeIsrc(isrc)
  if (canonical.startsWith(MEJAY_ISRC_PREFIX)) return 'MEJay-prefixed ISRCs can only be generated by MEJay'
  if (/^[A-Z]{2}[A-Z0-9]{3}[0-9]{2}00000$/.test(canonical)) return 'ISRC designation 00000 is not valid'
  return null
}

/**
 * Reads the generation prefix. ISRC_PREFIX=QTA3L alone is enough; ISRC_COUNTRY_CODE and
 * ISRC_REGISTRANT_CODE are optional and, when present, must describe the same prefix. Anything other
 * than MEJay's purchased QTA3L prefix fails closed, so a typo can never mint codes under another
 * registrant (or a doubled prefix such as "QTA3LA3L").
 */
export function readIsrcGenerationConfig(env: NodeJS.ProcessEnv): IsrcGenerationConfig | null {
  const prefix = env.ISRC_PREFIX?.trim().toUpperCase() || ''
  const countryCode = env.ISRC_COUNTRY_CODE?.trim().toUpperCase() || ''
  const registrantCode = env.ISRC_REGISTRANT_CODE?.trim().toUpperCase() || ''
  if (!prefix && !countryCode && !registrantCode) return null
  const effectivePrefix = prefix || `${countryCode}${registrantCode}`
  const consistent = effectivePrefix === MEJAY_ISRC_PREFIX
    && (!countryCode || countryCode === 'QT')
    && (!registrantCode || registrantCode === 'A3L')
  if (!consistent) {
    throw new Error('ISRC generation requires ISRC_PREFIX=QTA3L (optional ISRC_COUNTRY_CODE=QT and ISRC_REGISTRANT_CODE=A3L must match it)')
  }
  return {prefix: MEJAY_ISRC_PREFIX, countryCode: 'QT', registrantCode: 'A3L'}
}

export function normalizeIsrc(value: string): string {
  return value.trim().toUpperCase().replace(/[-\s]/g, '')
}

export function formatIsrc(value: string): string {
  const canonical = normalizeIsrc(value)
  if (!/^[A-Z]{2}[A-Z0-9]{3}[0-9]{7}$/.test(canonical)) return value
  return `${canonical.slice(0, 2)}-${canonical.slice(2, 5)}-${canonical.slice(5, 7)}-${canonical.slice(7)}`
}

export function buildGeneratedIsrc(prefix: 'QTA3L', assignmentYear: number, designation: number): string {
  if (!Number.isInteger(assignmentYear) || assignmentYear < 0 || assignmentYear > 99) throw new Error('Invalid ISRC assignment year')
  if (!Number.isInteger(designation) || designation < 1 || designation > 99999) throw new Error('Invalid ISRC designation')
  return `${prefix}${String(assignmentYear).padStart(2, '0')}${String(designation).padStart(5, '0')}`
}